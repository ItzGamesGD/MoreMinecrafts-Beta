#!/usr/bin/env python3
"""CAPTURE-TIME tool (needs the original feature refs; recovery itself never does).

For every preserved development state it records the original head SHA, head tree, merge base with the
frozen baseline, and the complete delta (A/M/D, mode, blob) in inactive/RECOVERY_MANIFEST.tsv, and stores every
delta blob that is not already present in the Grand Unified tree under inactive/<family>/state-blobs/<label>/.

Policy (security): a file that contains a complete gitleaks fingerprint (<40 hex>:<path>:<rule>:<line>), or is an
ignore-entry proposal, is NOT copied. One known false-positive literal is stored in a reversible transformed form
(inactive/TRANSFORMS.json). Large deterministic artifacts are regenerated by recipes (inactive/RECIPES.json).
"""
import csv, hashlib, json, os, re, subprocess, sys
ROOT = subprocess.check_output(["git", "rev-parse", "--show-toplevel"], text=True).strip()
BASE = "49747981ecc49f7f6b0a39fe62b23bd1a8d42d02"
def git(*a, binary=False):
    r = subprocess.run(["git", "-C", ROOT, *a], capture_output=True)
    return r.stdout if binary else r.stdout.decode("utf-8", "replace")
FPR = re.compile(rb"\b[0-9a-f]{40}:[^\s:`'\"]+:[a-z][a-z-]*:\d+")
STATES = [  # (family, label, ref)
 ("sky-mob","primary","origin/work/sky-mob-tower-integration-20261111"),
 ("sky-mob","variant-p2b-p2c","origin/claude/sky-mob-p2b-p2c-vwuur8"),
 ("sky-mob","variant-gametest-timing","origin/claude/sky-mob-gametest-timing-nn7o1h"),
 ("st01-o14-p7-p11","primary","origin/work/st01-o14-phase3-1-validation-20261109"),
 ("st01-phase4","primary","origin/claude/st01-pyramid-phase4-worldgen-roke2l"),
 ("st01-terrain-adaptation","primary","origin/research/st01-p8c3a-terrain-adaptation-20261111"),
 ("st05-controller-structure-mask","primary","origin/feat/st05-c4-structure-mask-20261030"),
 ("q1c-wither-skull","primary","origin/codex/q1c-pr128-p1-p2-repair-20261019"),
 ("client-qa-stage23b","primary","origin/codex/stage23b-cloud-live-client-qa"),
 ("validation-underground-kingdom-probe","primary","origin/experiment/underground-kingdom-worldgen-probe"),
 ("validation-st05-stage0-probes","primary","origin/validation/st05-stage0-a02-a03-20261030"),
 ("validation-st05-p0-probe","primary","origin/audit/st05-po25-review-package-20261102"),
 ("prc-p7-security-audit","primary","origin/audit/prc-p7d-security-verification-20261027"),
 ("drive-mirror","primary","origin/claude/moreminecrafts-mirror-gate-race-20261111"),
]
REGEN_PATHS = {  # path -> recipe id
 "tools/st05-p0-probe-01/inputs-v1.json":"st05-p0-materialize","tools/st05-p0-probe-01/schedules-v1.json":"st05-p0-materialize",
 "tools/st05-p0-probe-01/expected-traces-v1.json":"st05-p0-materialize","tools/st05-p0-probe-01/runplan-v1.json":"st05-p0-materialize",
 "tools/st05-p0-probe-01/oracle/goldens-v1.json":"st05-p0-oracle"}
POLICY_OMIT = re.compile(r"PROPOSED-gitleaksignore|\.gitleaksignore")
TRANSFORM = {"tools/st05-p0-probe-01/freeze_integrity.py":
  ("'ST05_STAGE0_P0_API_MAPPING'","('ST05_STAGE0_P0_API_MAPPING')")}  # identifier list flagged as generic-api-key; AST-identical
def main():
    # blobs already in the Grand Unified tree
    have = {}
    for line in git("ls-tree", "-r", "HEAD").splitlines():
        meta, p = line.split("\t", 1); have[meta.split()[2]] = p
    for dp, _, fs in os.walk(f"{ROOT}/inactive"):
        for f in fs:
            d = open(os.path.join(dp, f), "rb").read()
            have.setdefault(hashlib.sha1(b"blob %d\0" % len(d) + d).hexdigest(), os.path.relpath(os.path.join(dp, f), ROOT))
    rows, newfiles, omitted, transforms, regen = [], [], [], [], []
    for fam, label, ref in STATES:
        head = git("rev-parse", ref).strip(); tree = git("rev-parse", ref + "^{tree}").strip()
        mb = git("merge-base", BASE, ref).strip()
        for line in git("diff-tree", "-r", "--no-renames", mb, ref).splitlines():
            meta, p = line.split("\t", 1); om, nm, ob, nb, st = meta[1:].split()
            st = st[0]
            if st == "D": rows.append((fam, label, head, tree, mb, "D", "000000", "0"*40, p, "")); continue
            store = "GU"
            if p in REGEN_PATHS: store = "REGEN:" + REGEN_PATHS[p]; regen.append((p, nb))
            elif nb not in have:
                data = git("cat-file", "blob", nb, binary=True)
                if FPR.search(data) or POLICY_OMIT.search(p):
                    store = "OMITTED:fingerprint-or-ignore-entry"; omitted.append((fam, p, "contains complete gitleaks fingerprint / ignore-entry proposal"))
                else:
                    dest = f"{fam}/state-blobs/{label}/{p}"
                    if p in TRANSFORM:
                        frm, to = TRANSFORM[p]; t = data.decode().replace(frm, to).encode()
                        assert t != data; transforms.append(dict(family=fam, label=label, path=p, stored=dest, original_blob=nb, **{"from": frm, "to": to}))
                        data = t; store = "TRANSFORM"
                    os.makedirs(os.path.dirname(f"{ROOT}/inactive/{dest}"), exist_ok=True)
                    open(f"{ROOT}/inactive/{dest}", "wb").write(data)
                    newfiles.append((dest, hashlib.sha1(b"blob %d\0" % len(data) + data).hexdigest(), len(data), ref.replace("origin/",""), head[:8], p, store))
                    if store != "TRANSFORM": have[nb] = dest; store = "STATE_BLOB"
            rows.append((fam, label, head, tree, mb, st, nm, nb, p, store))
    with open(f"{ROOT}/inactive/RECOVERY_MANIFEST.tsv", "w") as f:
        f.write("family\tlabel\thead_sha\thead_tree\tmerge_base\tstatus\tmode\tblob\tpath\tstore\n")
        for r in rows: f.write("\t".join(r) + "\n")
    json.dump(transforms, open(f"{ROOT}/inactive/TRANSFORMS.json", "w"), indent=1)
    json.dump(omitted, open(f"{ROOT}/inactive/OMITTED.json", "w"), indent=1)
    json.dump(newfiles, open(f"{ROOT}/inactive/.newfiles.json", "w"))
    print("states", len(STATES), "delta rows", len(rows), "new blob files", len(newfiles), "omitted", len(omitted), "regen", len(regen), "transforms", len(transforms))
    for o in omitted: print(" OMIT", o[0], o[1])
main()
