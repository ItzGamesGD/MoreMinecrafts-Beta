/**
 * P2-D1 Crystal Bug (approved concept A, rock type): a static, opaque model on the vanilla silverfish layout.
 *
 * <p>Seven body segments run from the head (front, -Z) to the tail like the vanilla silverfish. Every segment is a
 * direct child of the root, and each crystal and leg is a child of its segment, so a later joint animation (D2) moves
 * them with the body. No animation is applied in D1. The entity's SCALE attribute (2.5, Q25) enlarges the render.
 *
 * <p>The 64x64 texture is generated by scripts/crystal-bug-validation/texture.py, whose UV atlas must match the
 * offsets below (it asserts that no regions overlap).
 */
final class CrystalBugRenderer extends MobRenderer<CrystalBug, LivingEntityRenderState, CrystalBugRenderer.CrystalBugModel> {
    static final ModelLayerLocation LAYER = new ModelLayerLocation(ModIds.id("crystal_bug"), "main");
    static final Identifier TEXTURE = ModIds.id("textures/entity/crystal_bug.png");

    CrystalBugRenderer(EntityRendererProvider.Context context) {
        super(context, new CrystalBugModel(context.bakeLayer(LAYER)), 0.3F);
    }

    static void register() {
        ModelLayerRegistry.registerModelLayer(LAYER, CrystalBugRenderer::createLayer);
        EntityRendererRegistry.register(SkyNormalMobs.CRYSTAL_BUG, CrystalBugRenderer::new);
    }

    @Override
    protected float getFlipDegrees() {
        return 180.0F; // vanilla silverfish death roll
    }

    @Override
    public Identifier getTextureLocation(LivingEntityRenderState state) {
        return TEXTURE;
    }

    @Override
    public LivingEntityRenderState createRenderState() {
        return new LivingEntityRenderState();
    }

    // ---- crystal atlas: one 32x15 block per colour, same internal layout ---------------------------------------
    private static final int TEAL = 0;
    private static final int SKY = 1;
    private static final int PURPLE = 2;
    private static final int PINK = 3;
    private static final int[][] COLOR_ORIGIN = {{0, 34}, {32, 34}, {0, 49}, {32, 49}};

    /** Shaft (w x h x w) plus a tapered tip (w x tipH x w shrunk by taper); u/v are offsets inside a colour block. */
    private enum Size {
        XL(3, 5, 0, 0, 2, 0, 10, 0.8F),
        L(2, 4, 12, 0, 2, 12, 8, 0.5F),
        M(2, 3, 20, 0, 2, 12, 8, 0.5F),
        S(1, 2, 28, 0, 1, 28, 4, 0.25F);

        final int w, h, u, v, tipH, tipU, tipV;
        final float taper;

        Size(int w, int h, int u, int v, int tipH, int tipU, int tipV, float taper) {
            this.w = w; this.h = h; this.u = u; this.v = v;
            this.tipH = tipH; this.tipU = tipU; this.tipV = tipV; this.taper = taper;
        }
    }

    private static int crystalCount;

    /** A crystal rooted at (x, y, z) on its segment, leaning by xRot (back +) / zRot (outward), twisted by yRot. */
    private static void crystal(PartDefinition segment, int color, Size size, float x, float y, float z,
                                float xRot, float yRot, float zRot) {
        int cu = COLOR_ORIGIN[color][0];
        int cv = COLOR_ORIGIN[color][1];
        float half = size.w / 2.0F;
        PartDefinition shaft = segment.addOrReplaceChild("crystal_" + crystalCount++, CubeListBuilder.create()
                        .texOffs(cu + size.u, cv + size.v)
                        .addBox(-half, -size.h, -half, size.w, size.h, size.w),
                PartPose.offsetAndRotation(x, y, z, xRot, yRot, zRot));
        // The tip only narrows (negative x/z deformation), giving each crystal a pointed top.
        shaft.addOrReplaceChild("tip", CubeListBuilder.create()
                        .texOffs(cu + size.tipU, cv + size.tipV)
                        .addBox(-half, -size.h - size.tipH, -half, size.w, size.tipH, size.w,
                                new CubeDeformation(-size.taper, 0.0F, -size.taper)),
                PartPose.ZERO);
    }

    private static PartDefinition segment(PartDefinition root, String name, int u, int v, int w, int h, int d,
                                          float bottomY, float zStart) {
        return root.addOrReplaceChild(name, CubeListBuilder.create().texOffs(u, v)
                        .addBox(-w / 2.0F, -h, 0.0F, w, h, d),
                PartPose.offset(0.0F, bottomY, zStart));
    }

    /** Short stubby rock leg pair under a segment, splayed outward. */
    private static void legs(PartDefinition segment, String name, float halfWidth, float z) {
        segment.addOrReplaceChild(name + "_right", CubeListBuilder.create().texOffs(10, 18)
                        .addBox(-1.0F, 0.0F, -1.0F, 2.0F, 2.0F, 2.0F),
                PartPose.offsetAndRotation(-halfWidth + 0.5F, -0.3F, z, 0.0F, 0.0F, 0.35F));
        segment.addOrReplaceChild(name + "_left", CubeListBuilder.create().texOffs(10, 18).mirror()
                        .addBox(-1.0F, 0.0F, -1.0F, 2.0F, 2.0F, 2.0F),
                PartPose.offsetAndRotation(halfWidth - 0.5F, -0.3F, z, 0.0F, 0.0F, -0.35F));
    }

    static LayerDefinition createLayer() {
        crystalCount = 0;
        MeshDefinition mesh = new MeshDefinition();
        PartDefinition root = mesh.getRoot();
        // Segments, head (-Z) to tail; bodies stand 2 px off the ground on the legs, the head rests a little lower.
        PartDefinition head = segment(root, "segment0", 0, 0, 6, 4, 4, 23.0F, -12.0F);
        PartDefinition s1 = segment(root, "segment1", 20, 0, 6, 4, 4, 22.0F, -8.0F);
        PartDefinition s2 = segment(root, "segment2", 40, 0, 8, 5, 4, 22.0F, -4.0F);
        PartDefinition s3 = segment(root, "segment3", 0, 9, 8, 5, 4, 22.0F, 0.0F);
        PartDefinition s4 = segment(root, "segment4", 24, 9, 7, 4, 4, 22.0F, 4.0F);
        PartDefinition s5 = segment(root, "segment5", 46, 9, 5, 3, 3, 22.3F, 8.0F);
        PartDefinition s6 = segment(root, "segment6", 0, 18, 3, 2, 2, 22.6F, 11.0F);

        legs(s1, "leg1", 3.0F, 2.0F);
        legs(s2, "leg2", 4.0F, 2.0F);
        legs(s3, "leg3", 4.0F, 2.0F);
        legs(s4, "leg4", 3.5F, 2.0F);

        // Crystals: teal / sky blue toward the head, purple / pink toward the tail, irregular sizes and angles.
        crystal(head, TEAL, Size.S, -1.5F, -4.0F, 3.0F, -0.15F, 0.3F, -0.24F);
        crystal(head, SKY, Size.S, 1.4F, -4.0F, 2.6F, -0.05F, -0.4F, 0.28F);

        crystal(s1, TEAL, Size.L, 1.0F, -4.0F, 2.0F, -0.2F, 0.5F, 0.17F);
        crystal(s1, SKY, Size.M, -1.6F, -4.0F, 2.4F, 0.1F, -0.3F, -0.28F);
        crystal(s1, TEAL, Size.S, -3.0F, -2.5F, 1.87F, 0.05F, 0.2F, -0.66F);
        crystal(s1, SKY, Size.S, 3.0F, -2.6F, 1.33F, -0.1F, -0.6F, 0.63F);
        crystal(s1, TEAL, Size.S, 0.2F, -4.0F, 0.6F, -0.25F, 0.2F, 0.0F);

        crystal(s2, SKY, Size.XL, 0.0F, -5.0F, 2.0F, -0.1F, 0.4F, 0.03F);
        crystal(s2, TEAL, Size.M, -2.6F, -5.0F, 2.67F, 0.15F, 0.1F, -0.32F);
        crystal(s2, PURPLE, Size.L, 2.6F, -5.0F, 1.6F, 0.05F, -0.3F, 0.28F);
        crystal(s2, SKY, Size.S, -4.0F, -3.0F, 1.33F, -0.1F, 0.5F, -0.7F);
        crystal(s2, TEAL, Size.M, 4.0F, -3.0F, 2.67F, 0.1F, 0.2F, 0.73F);
        crystal(s2, SKY, Size.M, 0.9F, -5.0F, 3.4F, 0.2F, -0.6F, 0.15F);

        crystal(s3, PURPLE, Size.XL, 0.3F, -5.0F, 2.0F, 0.12F, -0.35F, -0.06F);
        crystal(s3, SKY, Size.L, -2.6F, -5.0F, 1.33F, -0.1F, 0.6F, -0.35F);
        crystal(s3, PINK, Size.M, 2.6F, -5.0F, 2.67F, 0.2F, 0.3F, 0.35F);
        crystal(s3, PURPLE, Size.M, -4.0F, -3.0F, 2.0F, 0.05F, -0.2F, -0.73F);
        crystal(s3, SKY, Size.S, 4.0F, -3.0F, 1.6F, 0.0F, 0.4F, 0.7F);
        crystal(s3, TEAL, Size.S, -1.2F, -5.0F, 3.4F, 0.15F, 0.5F, -0.2F);

        crystal(s4, PINK, Size.L, 0.0F, -4.0F, 2.0F, 0.2F, 0.2F, 0.07F);
        crystal(s4, PURPLE, Size.M, -2.0F, -4.0F, 2.67F, 0.1F, -0.5F, -0.35F);
        crystal(s4, PURPLE, Size.M, 2.0F, -4.0F, 1.33F, 0.25F, 0.4F, 0.32F);
        crystal(s4, PINK, Size.S, -3.5F, -2.5F, 2.0F, 0.0F, 0.3F, -0.7F);
        crystal(s4, PURPLE, Size.S, 3.5F, -2.5F, 2.0F, 0.1F, -0.3F, 0.7F);
        crystal(s4, PINK, Size.S, 0.9F, -4.0F, 3.4F, 0.3F, -0.5F, 0.2F);

        crystal(s5, PINK, Size.M, 0.0F, -3.0F, 1.33F, 0.35F, -0.2F, -0.07F);
        crystal(s5, PURPLE, Size.S, -1.8F, -3.0F, 1.6F, 0.3F, 0.4F, -0.35F);
        crystal(s5, PINK, Size.S, 1.8F, -3.0F, 1.07F, 0.4F, -0.4F, 0.35F);

        crystal(s6, PINK, Size.S, 0.0F, -2.0F, 1.33F, 0.6F, 0.3F, 0.0F);
        return LayerDefinition.create(mesh, 64, 64);
    }

    /** Static D1 model: no animation is applied (joint and walk animation are the separate D2 stage). */
    static final class CrystalBugModel extends EntityModel<LivingEntityRenderState> {
        CrystalBugModel(ModelPart root) {
            super(root);
        }
    }
}
