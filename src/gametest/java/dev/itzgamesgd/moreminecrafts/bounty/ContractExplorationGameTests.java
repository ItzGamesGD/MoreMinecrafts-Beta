/**
 * Owner decision D2 (2026-10-25): multi-location exploration counted on genuine vanilla structure instances detected by
 * the server, across chunk boundaries, reconnect, item transfer and legacy items.
 */
public final class ContractExplorationGameTests implements CustomTestMethodInvoker {
    private static final String MINESHAFT = "minecraft:mineshaft";
    private static int nextOrigin = 0;

    /** A real mineshaft StructureStart generated by vanilla and registered in its chunks as world generation would. */
    private static StructureStart mineshaft(GameTestHelper ctx) {
        ServerLevel level = ctx.getLevel();
        var holder = level.registryAccess().lookupOrThrow(Registries.STRUCTURE)
                .getOrThrow(ResourceKey.create(Registries.STRUCTURE, Identifier.parse(MINESHAFT)));
        var generator = level.getChunkSource().getGenerator();
        var randomState = level.getChunkSource().randomState();
        for (int attempt = 0; attempt < 32; attempt++) {
            ChunkPos origin;
            synchronized (ContractExplorationGameTests.class) {
                origin = new ChunkPos(-7000 - 40 * nextOrigin, 7000);
                nextOrigin++;
            }
            StructureStart start = holder.value().generate(holder, level.dimension(), level.registryAccess(), generator,
                    generator.getBiomeSource(), randomState.createClimateSampler(
                            net.minecraft.world.level.levelgen.densityfunction.SamplerContext.EMPTY_UNCACHED),
                    randomState, level.getServer().getStructureTemplateManager(), level.getSeed(), origin, 0, level,
                    biome -> true);
            if (!start.isValid()) continue;
            var box = start.getBoundingBox();
            for (int cx = box.minX() >> 4; cx <= box.maxX() >> 4; cx++)
                for (int cz = box.minZ() >> 4; cz <= box.maxZ() >> 4; cz++) {
                    var chunk = level.getChunk(cx, cz);
                    chunk.addReferenceForStructure(holder.value(), origin.pack());
                    if (cx == origin.x() && cz == origin.z()) chunk.setStartForStructure(holder.value(), start);
                }
            return start;
        }
        throw new IllegalStateException("vanilla produced no valid mineshaft");
    }

    /** Points inside two pieces of one structure that lie in different chunks. */
    private static BlockPos[] twoChunks(GameTestHelper ctx, StructureStart start) {
        BlockPos first = start.getPieces().getFirst().getBoundingBox().getCenter();
        for (var piece : start.getPieces()) {
            BlockPos other = piece.getBoundingBox().getCenter();
            if ((other.getX() >> 4) != (first.getX() >> 4) || (other.getZ() >> 4) != (first.getZ() >> 4))
                return new BlockPos[]{first, other};
        }
        ctx.fail("the mineshaft never left its first chunk");
        return null;
    }

    private static void standAt(ServerPlayer player, BlockPos pos) {
        player.setPos(pos.getX() + 0.5, pos.getY(), pos.getZ() + 0.5);
        ContractObjectives.detectStructure(player);
    }

    private static ContractData explore(String id, int required) {
        return new ContractData(id, ContractData.Tier.ADVANCED, ContractData.Status.ACCEPTED,
                List.of(new ContractData.Objective(ContractData.Category.EXPLORATION, MINESHAFT, required, 0)),
                new ContractData.Reward(25, "minecraft:coal", 16));
    }

    private static int slotOf(ServerPlayer player, String id) {
        for (int slot = 0; slot < player.getInventory().getContainerSize(); slot++) {
            ContractData data = ContractStacks.read(player.getInventory().getItem(slot));
            if (data != null && data.id().equals(id)) return slot;
        }
        return -1;
    }

    private static ContractData.Objective objective(ServerPlayer player, String id) {
        return ContractStacks.read(player.getInventory().getItem(slotOf(player, id))).objectives().getFirst();
    }

    @GameTest(maxTicks = 400)
    public void distinctInstancesCountAndOneInstanceCountsOnceAcrossItsChunks(GameTestHelper ctx) {
        StructureStart first = mineshaft(ctx);
        StructureStart second = mineshaft(ctx);
        BlockPos[] firstPoints = twoChunks(ctx, first);
        ServerPlayer player = ctx.makeMockServerPlayerInLevel();
        String id = UUID.randomUUID().toString();
        player.getInventory().setItem(0, ContractStacks.create(explore(id, 2)));

        standAt(player, firstPoints[0]);
        ctx.assertTrue(objective(player, id).progress() == 1, "entering a real mineshaft counts");
        standAt(player, firstPoints[1]);
        ctx.assertTrue(objective(player, id).progress() == 1, "another chunk of the same mineshaft is the same instance");
        standAt(player, firstPoints[0]);
        ctx.assertTrue(objective(player, id).progress() == 1, "re-entering the same instance does not count again");
        ctx.assertTrue(!ContractService.act(player, slotOf(player, id), id, ContractService.Action.COMPLETE),
                "one of two locations cannot complete the contract");

        standAt(player, second.getPieces().getFirst().getBoundingBox().getCenter());
        ctx.assertTrue(objective(player, id).progress() == 2, "a genuinely different mineshaft counts");
        ctx.assertTrue(objective(player, id).visited().size() == 2, "two distinct instances recorded");
        ctx.assertTrue(ContractService.act(player, slotOf(player, id), id, ContractService.Action.COMPLETE), "complete");
        ctx.assertTrue(player.getInventory().countItem(Items.EMERALD) == 25, "paid once");
        ctx.succeed();
    }

    @GameTest(maxTicks = 400)
    public void transferredContractKeepsVisitedInstancesAndPlayersStayIsolated(GameTestHelper ctx) {
        StructureStart first = mineshaft(ctx);
        StructureStart second = mineshaft(ctx);
        BlockPos inFirst = first.getPieces().getFirst().getBoundingBox().getCenter();
        BlockPos inSecond = second.getPieces().getFirst().getBoundingBox().getCenter();
        ServerPlayer giver = ctx.makeMockServerPlayerInLevel();
        ServerPlayer receiver = ctx.makeMockServerPlayerInLevel();
        String shared = UUID.randomUUID().toString();
        String own = UUID.randomUUID().toString();
        giver.getInventory().setItem(0, ContractStacks.create(explore(shared, 2)));
        receiver.getInventory().setItem(0, ContractStacks.create(explore(own, 2)));

        standAt(giver, inFirst);
        ctx.assertTrue(objective(giver, shared).progress() == 1, "giver credited");
        ctx.assertTrue(objective(receiver, own).progress() == 0, "a player who did not enter is not credited");

        receiver.getInventory().setItem(1, giver.getInventory().removeItemNoUpdate(0));
        standAt(receiver, inFirst);
        ctx.assertTrue(objective(receiver, shared).progress() == 1,
                "an instance the previous holder visited does not count again after transfer");
        ctx.assertTrue(objective(receiver, own).progress() == 1, "the receiver's own contract counts that instance for them");
        standAt(receiver, inSecond);
        ctx.assertTrue(objective(receiver, shared).progress() == 2 && objective(receiver, own).progress() == 2,
                "a new instance advances every accepted contract the holder carries");
        ctx.assertTrue(ContractService.act(receiver, slotOf(receiver, shared), shared, ContractService.Action.COMPLETE),
                "the receiver completes the transferred contract");
        ctx.assertTrue(giver.getInventory().countItem(Items.EMERALD) == 0 && receiver.getInventory().countItem(Items.EMERALD) == 25,
                "only the redeeming holder is paid");
        ctx.succeed();
    }

    private static ServerPlayer connect(GameTestHelper ctx, UUID id, boolean loadFromDisk) {
        ServerLevel level = ctx.getLevel();
        var profile = new com.mojang.authlib.GameProfile(id, "explore-" + id.toString().substring(0, 8));
        var cookie = net.minecraft.server.network.CommonListenerCookie.createInitial(profile, false);
        var player = new ServerPlayer(level.getServer(), level, cookie.gameProfile(), cookie.clientInformation());
        if (loadFromDisk) {
            var saved = level.getServer().getPlayerList().loadPlayerData(player.nameAndId());
            ctx.assertTrue(saved.isPresent(), "player data was saved on disconnect");
            player.load(net.minecraft.world.level.storage.TagValueInput.create(
                    net.minecraft.util.ProblemReporter.DISCARDING, player.registryAccess(), saved.orElseThrow()));
        }
        var connection = new net.minecraft.network.Connection(net.minecraft.network.protocol.PacketFlow.SERVERBOUND);
        new io.netty.channel.embedded.EmbeddedChannel(connection);
        level.getServer().getPlayerList().placeNewPlayer(connection, player, cookie);
        player.setGameMode(net.minecraft.world.level.GameType.SURVIVAL);
        return player;
    }

    @GameTest(maxTicks = 400)
    public void multiLocationProgressSurvivesReconnect(GameTestHelper ctx) {
        StructureStart first = mineshaft(ctx);
        StructureStart second = mineshaft(ctx);
        StructureStart third = mineshaft(ctx);
        UUID playerId = UUID.randomUUID();
        String id = UUID.randomUUID().toString();
        ServerPlayer player = connect(ctx, playerId, false);
        player.getInventory().setItem(0, ContractStacks.create(explore(id, 3)));
        standAt(player, first.getPieces().getFirst().getBoundingBox().getCenter());
        standAt(player, second.getPieces().getFirst().getBoundingBox().getCenter());
        ContractData.Objective before = objective(player, id);
        ctx.assertTrue(before.progress() == 2 && before.visited().size() == 2, "two of three locations before disconnect");
        ctx.getLevel().getServer().getPlayerList().remove(player);

        ServerPlayer back = connect(ctx, playerId, true);
        ctx.assertTrue(before.equals(objective(back, id)), "progress and visited instances survive reconnect");
        standAt(back, second.getPieces().getFirst().getBoundingBox().getCenter());
        ctx.assertTrue(objective(back, id).progress() == 2, "an instance visited before the reconnect is not counted again");
        standAt(back, third.getPieces().getFirst().getBoundingBox().getCenter());
        ctx.assertTrue(objective(back, id).progress() == 3, "a third distinct instance completes the objective");
        ItemStack copy = back.getInventory().getItem(slotOf(back, id)).copy();
        ctx.assertTrue(ContractService.act(back, slotOf(back, id), id, ContractService.Action.COMPLETE), "completes after reconnect");
        back.getInventory().setItem(8, copy);
        ctx.assertTrue(!ContractService.act(back, 8, id, ContractService.Action.COMPLETE), "a copy cannot redeem again");
        ctx.assertTrue(back.getInventory().countItem(Items.EMERALD) == 25, "paid once");
        ctx.getLevel().getServer().getPlayerList().remove(back);
        ctx.succeed();
    }

    @GameTest(maxTicks = 400)
    public void legacySingleLocationItemStillCompletesWithOneRealInstance(GameTestHelper ctx) {
        StructureStart start = mineshaft(ctx);
        String id = UUID.randomUUID().toString();
        // An item stack as builds before D2 saved it: required 1 and no visited list.
        ItemStack stack = ContractStacks.create(explore(id, 1));
        var ops = ctx.getLevel().registryAccess().createSerializationContext(net.minecraft.nbt.NbtOps.INSTANCE);
        var encoded = (net.minecraft.nbt.CompoundTag) ItemStack.CODEC.encodeStart(ops, stack).getOrThrow();
        var objectiveTag = encoded.getCompoundOrEmpty("components").getCompoundOrEmpty("moreminecrafts:contract")
                .getListOrEmpty("objectives").getCompoundOrEmpty(0);
        objectiveTag.remove("visited");
        ctx.assertTrue(!objectiveTag.contains("visited") && objectiveTag.getIntOr("required", 0) == 1,
                "fixture is in the legacy shape");
        ItemStack restored = ItemStack.CODEC.parse(ops, encoded).getOrThrow();
        ContractData data = ContractStacks.read(restored);
        ctx.assertTrue(data != null && data.objectives().getFirst().required() == 1, "the legacy item decodes unchanged");

        ServerPlayer player = ctx.makeMockServerPlayerInLevel();
        player.getInventory().setItem(0, restored);
        BlockPos[] points = twoChunks(ctx, start);
        standAt(player, points[0]);
        standAt(player, points[1]);
        ctx.assertTrue(objective(player, id).progress() == 1, "one instance, entered in two chunks, counts once");
        ctx.assertTrue(ContractService.act(player, 0, id, ContractService.Action.COMPLETE), "the legacy contract completes");
        ctx.assertTrue(!ContractService.act(player, 0, id, ContractService.Action.COMPLETE), "and only once");
        ctx.assertTrue(player.getInventory().countItem(Items.EMERALD) == 25, "paid once");
        ctx.succeed();
    }

    @GameTest
    public void generatedMultiLocationContractCompletesThroughDistinctEntries(GameTestHelper ctx) {
        ServerPlayer player = ctx.makeMockServerPlayerInLevel();
        net.minecraft.util.RandomSource random = net.minecraft.util.RandomSource.create(77L);
        ContractData data = null;
        for (int i = 0; i < 10_000 && data == null; i++) {
            ContractData candidate = ContractGenerator.generate(UUID.randomUUID().toString(), ContractData.Tier.ADVANCED, random);
            if (candidate.objectives().stream().allMatch(o -> o.category() == ContractData.Category.EXPLORATION)
                    && candidate.objectives().stream().anyMatch(o -> o.required() == 3)) data = candidate;
        }
        ctx.assertTrue(data != null, "an all-exploration Advanced contract with a three-location objective was generated");
        player.getInventory().setItem(0, ContractStacks.create(data));
        String id = data.id();
        ctx.assertTrue(ContractService.act(player, 0, id, ContractService.Action.ACCEPT), "accept");
        for (ContractData.Objective objective : data.objectives())
            for (int repeat = 0; repeat < 5; repeat++)
                ContractService.enterStructure(player, objective.target(), "minecraft:overworld:repeat");
        ctx.assertTrue(!ContractService.act(player, 0, id, ContractService.Action.COMPLETE),
                "repeated entries into one instance cannot satisfy multi-location objectives");
        for (ContractData.Objective objective : data.objectives())
            for (int visit = 0; visit < objective.required(); visit++)
                ContractService.enterStructure(player, objective.target(), "minecraft:overworld:" + visit);
        ctx.assertTrue(ContractService.act(player, 0, id, ContractService.Action.COMPLETE), "distinct entries complete it");
        ctx.succeed();
    }

    @Override public void invokeTestMethod(GameTestHelper context, Method method) throws ReflectiveOperationException {
        method.invoke(this, context);
    }
}
