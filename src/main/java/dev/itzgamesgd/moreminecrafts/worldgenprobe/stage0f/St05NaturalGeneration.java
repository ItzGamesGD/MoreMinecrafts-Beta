/**
 * ST-05 natural generation of the Ancient Colosseum in ordinary play worlds. This class only <b>drives</b> the already-approved pipeline:
 * <ol>
 *   <li><b>Reservation</b> (Stage 0-D/0-E, unchanged): per 256x256 ownership region, chamber identification (24x24x12 core, DISK32), structure exclusion, deterministic greedy
 *       256-block spacing, ONE 75% roll per spacing survivor, post-roll preflight. Candidates that depend on unobserved or unresolved neighbours are BLOCKED_BY_UNRESOLVED and are never
 *       reserved; a scan observes a 5x5 region universe so the scanned centre region never touches the universe border. The roll, priority and spacing are the same pure functions
 *       the Stage 0-E evidence used, so identical seeds give identical reservations regardless of where players walk.</li>
 *   <li><b>Construction</b> (Stage 0-F, unchanged): {@link St05Stage0FLive#handle} (journaled plan / apply / verify / quarantine, then {@code ColosseumRuntime.registerArena}).
 *       A journal state that is already terminal is never rebuilt and a PLANNED / APPLYING one is recovered by the same journal code.</li>
 * </ol>
 * Execution model: the expensive column-noise scan runs on background threads (the same {@code getBaseColumn} sampling the probes used; no chunk is generated by it). Everything that touches
 * blocks, tickets or the registry runs on the server thread from {@code END_SERVER_TICK}, one reservation at a time; chunks of the arena area are first requested through forced-chunk tickets and
 * construction starts only after they are all FULL, so the server thread never blocks on chunk generation. The decision records are persisted per region (atomic replace) so a restart neither
 * rescans nor rerolls.
 */
public final class St05NaturalGeneration {
    private St05NaturalGeneration() { }

    private static final Logger LOG = LoggerFactory.getLogger("moreminecrafts/st05-natural");

    // approved production parameters (Stage 0-F owner decisions: 24x24x12 core, DISK32); band is the Stage 0-D/0-E snapshot band
    static final Params PARAMS = new Params("C_24x24x12", 24, 12);
    static final Measure MEASURE = Measure.DISK32;
    static final int Y0 = -64, H = 80;
    static final int UNIVERSE_RADIUS = 2;                 // 5x5 regions observed around the scanned region
    static final int TRIGGER_BLOCKS = 192;                // a region is scanned / an arena is built only when a player is this close (XZ)
    static final String SNAPSHOT = "PLAN_BASE_COLUMN_v1";

    private static final int TILE = ChamberCore.OWN;       // noise tiles are one ownership region wide
    private static final int TICK_PERIOD = 20;

    /** Mutable run state (server thread unless noted). */
    private static final class Runtime {
        final MinecraftServer server; final ServerLevel level; final long seed;
        final Path regionDir; final Journal journal; final St05Stage0FLive.LevelWorld world;
        final Map<Long, List<St05Stage0FLive.Res>> reserved = new HashMap<>();   // region key -> reservations (loaded / scanned)
        final Set<Long> scanned = new HashSet<>(), scanning = new HashSet<>();
        final ExecutorService scanThread = Executors.newSingleThreadExecutor(r -> { Thread t = new Thread(r, "st05-natural-scan"); t.setDaemon(true); t.setPriority(Thread.MIN_PRIORITY); return t; });
        final ExecutorService noisePool;
        final Map<Long, BitSet> tiles = java.util.Collections.synchronizedMap(new LinkedHashMap<>(64, 0.75f, true) {
            @Override protected boolean removeEldestEntry(Map.Entry<Long, BitSet> e) { return size() > 96; }
        });
        final Map<Long, Observation> observations = java.util.Collections.synchronizedMap(new LinkedHashMap<>(64, 0.75f, true) {
            @Override protected boolean removeEldestEntry(Map.Entry<Long, Observation> e) { return size() > 96; }
        });
        // construction state machine
        St05Stage0FLive.Res current; long currentSince; boolean currentHeld;
        final Set<String> finished = new HashSet<>();
        volatile Throwable scanError;
        Runtime(MinecraftServer s, ServerLevel l, Path root) throws IOException {
            server = s; level = l; seed = l.getSeed();
            regionDir = root.resolve("regions");
            Files.createDirectories(regionDir);
            journal = new Journal(root.resolve("construction"));
            world = new St05Stage0FLive.LevelWorld(s, l);
            int threads = Math.max(1, Math.min(3, java.lang.Runtime.getRuntime().availableProcessors() - 1));
            noisePool = Executors.newFixedThreadPool(threads, r -> { Thread t = new Thread(r, "st05-natural-noise"); t.setDaemon(true); t.setPriority(Thread.MIN_PRIORITY); return t; });
        }
    }

    private static volatile Runtime RT;

    public static void initialize() {
        if (Boolean.getBoolean("fabric-api.gametest") || "false".equalsIgnoreCase(System.getProperty("mm.st05.natural"))) return;
        ServerLifecycleEvents.SERVER_STARTED.register(St05NaturalGeneration::start);
        ServerLifecycleEvents.SERVER_STOPPING.register(s -> stop());
        ServerTickEvents.END_SERVER_TICK.register(St05NaturalGeneration::tick);
    }

    private static void start(MinecraftServer server) {
        try {
            ServerLevel level = server.overworld();
            Runtime rt = new Runtime(server, level, server.getWorldPath(LevelResource.DATA).resolve("moreminecrafts-st05").resolve("natural"));
            for (Path p : (Iterable<Path>) Files.list(rt.regionDir)::iterator) {
                String n = p.getFileName().toString();
                if (!n.startsWith("r_") || !n.endsWith(".txt")) continue;
                int[] rr = parseRegionName(n);
                if (rr == null) continue;
                RegionFile f = readRegion(p, rt.seed);
                if (f == null) { quarantine(p); continue; }
                rt.scanned.add(key(rr[0], rr[1]));
                rt.reserved.put(key(rr[0], rr[1]), f.reservations);
            }
            RT = rt;
            LOG.info("[ST05-NATURAL] started seed={} regions_loaded={} state_dir={}", rt.seed, rt.scanned.size(), rt.regionDir.getParent());
        } catch (Exception e) {
            LOG.error("[ST05-NATURAL] failed to start; natural generation disabled for this run", e);
        }
    }

    private static void stop() {
        Runtime rt = RT;
        if (rt == null) return;
        RT = null;
        rt.scanThread.shutdownNow();
        rt.noisePool.shutdownNow();
        if (rt.current != null) {
            try { St05Stage0FLive.forceChunks(rt.level, rt.current, false); } catch (Throwable ignored) { }
        }
    }

    // ------------------------------------------------------------------------------------------------ tick
    private static void tick(MinecraftServer server) {
        Runtime rt = RT;
        if (rt == null || server.getTickCount() % TICK_PERIOD != 0) return;
        try {
            if (rt.scanError != null) { LOG.error("[ST05-NATURAL] scan failed", rt.scanError); rt.scanError = null; }
            // 1. scan scheduling (one background scan at a time; nearest region first)
            if (rt.scanning.isEmpty()) {
                int[] next = nextRegionToScan(rt);
                if (next != null) startScan(rt, next[0], next[1]);
            }
            // 2. construction state machine (server thread, one reservation at a time)
            constructionStep(rt);
        } catch (Throwable t) {
            LOG.error("[ST05-NATURAL] tick failure", t);
        }
    }

    private static List<int[]> focusPoints(Runtime rt) {
        List<int[]> pts = new ArrayList<>();
        String f = System.getProperty("mm.st05.natural.focus");   // headless validation: "x,z" acts as a virtual player
        if (f != null) { String[] p = f.split(","); pts.add(new int[]{Integer.parseInt(p[0].trim()), Integer.parseInt(p[1].trim())}); }
        for (ServerPlayer p : rt.server.getPlayerList().getPlayers()) if (p.level() == rt.level) pts.add(new int[]{p.blockPosition().getX(), p.blockPosition().getZ()});
        return pts;
    }

    private static int[] nextRegionToScan(Runtime rt) {
        long bestD = Long.MAX_VALUE; int[] best = null;
        for (int[] pt : focusPoints(rt)) {
            for (int rx = Math.floorDiv(pt[0] - TRIGGER_BLOCKS, TILE); rx <= Math.floorDiv(pt[0] + TRIGGER_BLOCKS, TILE); rx++)
                for (int rz = Math.floorDiv(pt[1] - TRIGGER_BLOCKS, TILE); rz <= Math.floorDiv(pt[1] + TRIGGER_BLOCKS, TILE); rz++) {
                    if (rt.scanned.contains(key(rx, rz))) continue;
                    long dx = rx * (long) TILE + TILE / 2 - pt[0], dz = rz * (long) TILE + TILE / 2 - pt[1], d = dx * dx + dz * dz;
                    if (d < bestD) { bestD = d; best = new int[]{rx, rz}; }
                }
        }
        return best;
    }

    // ------------------------------------------------------------------------------------------------ scan (background)
    private static void startScan(Runtime rt, int rx, int rz) {
        long k = key(rx, rz);
        rt.scanning.add(k);
        LOG.info("[ST05-NATURAL] scan start region={},{}", rx, rz);
        rt.scanThread.submit(() -> {
            try {
                long t0 = System.nanoTime();
                RegionFile rf = scanRegion(rt, rx, rz);
                writeRegion(rt.regionDir.resolve("r_" + rx + "_" + rz + ".txt"), rf);
                rt.server.execute(() -> {
                    rt.reserved.put(k, rf.reservations);
                    rt.scanned.add(k);
                    rt.scanning.remove(k);
                    LOG.info("[ST05-NATURAL] scan done region={},{} ms={} reserved={} summary={}", rx, rz, (System.nanoTime() - t0) / 1_000_000, rf.reservations.size(), rf.summary);
                });
            } catch (Throwable t) {
                rt.scanError = t;
                rt.server.execute(() -> rt.scanning.remove(k));
            }
        });
    }

    private static BitSet tile(Runtime rt, int tx, int tz) throws Exception {
        long k = key(tx, tz);
        BitSet cached = rt.tiles.get(k);
        if (cached != null) return cached;
        var gen = rt.level.getChunkSource().getGenerator();
        var rs = rt.level.getChunkSource().randomState();
        BitSet bits = new BitSet(TILE * TILE * H);
        List<Future<BitSet>> fs = new ArrayList<>();
        int stripe = 16;
        for (int x0 = 0; x0 < TILE; x0 += stripe) {
            final int xs = x0;
            fs.add(rt.noisePool.submit(() -> {
                BitSet part = new BitSet(stripe * TILE * H);
                for (int x = xs; x < xs + stripe; x++) for (int z = 0; z < TILE; z++) {
                    NoiseColumn col = gen.getBaseColumn(tx * TILE + x, tz * TILE + z, rt.level, rs);
                    for (int y = 0; y < H; y++) if (col.getBlock(Y0 + y).isAir()) part.set(((x - xs) * TILE + z) * H + y);
                }
                return part;
            }));
        }
        for (int i = 0; i < fs.size(); i++) {
            BitSet part = fs.get(i).get();
            int base = i * stripe * TILE * H;
            for (int b = part.nextSetBit(0); b >= 0; b = part.nextSetBit(b + 1)) bits.set(base + b);
        }
        rt.tiles.put(k, bits);
        return bits;
    }

    /** The Stage 0-D window of region (rx,rz): its 256x256 own area plus the 128-block margin, assembled from noise tiles (identical to {@code planWindow}). */
    private static Window window(Runtime rt, int rx, int rz) throws Exception {
        int n = ChamberCore.OWN + 2 * ChamberCore.MARGIN, ox = rx * ChamberCore.OWN - ChamberCore.MARGIN, oz = rz * ChamberCore.OWN - ChamberCore.MARGIN;
        boolean[] open = new boolean[n * n * H];
        for (int tx = Math.floorDiv(ox, TILE); tx <= Math.floorDiv(ox + n - 1, TILE); tx++)
            for (int tz = Math.floorDiv(oz, TILE); tz <= Math.floorDiv(oz + n - 1, TILE); tz++) {
                BitSet t = tile(rt, tx, tz);
                for (int x = Math.max(ox, tx * TILE); x < Math.min(ox + n, tx * TILE + TILE); x++)
                    for (int z = Math.max(oz, tz * TILE); z < Math.min(oz + n, tz * TILE + TILE); z++) {
                        int src = ((x - tx * TILE) * TILE + (z - tz * TILE)) * H, dst = ((x - ox) * n + (z - oz)) * H;
                        for (int y = t.nextSetBit(src); y >= 0 && y < src + H; y = t.nextSetBit(y + 1)) open[dst + (y - src)] = true;
                    }
            }
        return new Window(ox, Y0, oz, n, n, H, open, SNAPSHOT);
    }

    private static Observation observe(Runtime rt, int rx, int rz) throws Exception {
        long k = key(rx, rz);
        Observation o = rt.observations.get(k);
        if (o != null) return o;
        Window w = window(rt, rx, rz);
        o = new Observation(rx, rz, ChamberCore.extract(w, PARAMS, rt.seed, rx, rz, new ChamberCore.ExtractStats()), w.digest());
        rt.observations.put(k, o);
        return o;
    }

    /** Runs the unchanged Stage 0-D/0-E pipeline over the 5x5 universe centred on (rx,rz) and keeps only decisions for chambers owned by (rx,rz). */
    private static RegionFile scanRegion(Runtime rt, int rx, int rz) throws Exception {
        List<Observation> obs = new ArrayList<>();
        for (int x = rx - UNIVERSE_RADIUS; x <= rx + UNIVERSE_RADIUS; x++) for (int z = rz - UNIVERSE_RADIUS; z <= rz + UNIVERSE_RADIUS; z++) obs.add(observe(rt, x, z));
        ChamberCore.Resolution res = ChamberCore.resolve(obs, PARAMS, rt.seed);
        int[] universe = {(rx - UNIVERSE_RADIUS) * ChamberCore.OWN, (rz - UNIVERSE_RADIUS) * ChamberCore.OWN, (rx + UNIVERSE_RADIUS + 1) * ChamberCore.OWN, (rz + UNIVERSE_RADIUS + 1) * ChamberCore.OWN};
        NaturalEnv env = new NaturalEnv(rt.level);
        PlacementPipeline.Result pr = PlacementPipeline.run(res, rt.seed, MEASURE, universe, env);
        RegionFile rf = new RegionFile();
        rf.seed = rt.seed;
        Map<String, Integer> sum = new TreeMap<>();
        for (Chamber c : res.chambers.values()) {
            if (c.ownerRx != rx || c.ownerRz != rz) continue;
            String st = pr.status.getOrDefault(c.id, "UNSET");
            sum.merge(st, 1, Integer::sum);
            rf.lines.add(Long.toHexString(c.id) + " " + st + " " + pr.reason.getOrDefault(c.id, "-"));
            if (st.equals("PLACEMENT_RESERVED"))
                rf.reservations.add(new St05Stage0FLive.Res(Long.toHexString(c.id), c.diskCx, c.diskCz, c.diskFloorY));
        }
        rf.summary = sum.toString();
        if (!pr.invariantViolations.isEmpty()) throw new IllegalStateException("pipeline invariant violations: " + pr.invariantViolations);
        return rf;
    }

    /** Placement environment: structure exclusion from STRUCTURE_STARTS and the post-roll final-terrain preflight (fluid only), as in the Stage 0-E live run. */
    private static final class NaturalEnv implements PlacementPipeline.Env {
        final ServerLevel level;
        final Map<Long, List<int[]>> chunkBoxes = new HashMap<>();
        NaturalEnv(ServerLevel level) { this.level = level; }

        List<int[]> boxesOf(int cxk, int czk) {
            return chunkBoxes.computeIfAbsent(((long) cxk << 32) ^ (czk & 0xFFFFFFFFL), k -> {
                ChunkAccess ch = level.getChunk(cxk, czk, ChunkStatus.STRUCTURE_STARTS, true);
                List<int[]> out = new ArrayList<>();
                for (var e : ch.getAllStarts().entrySet()) {
                    StructureStart st = e.getValue();
                    if (!st.isValid()) continue;
                    for (var piece : st.getPieces()) { var b = piece.getBoundingBox(); out.add(new int[]{b.minX(), b.minZ(), b.maxX(), b.maxZ()}); }
                }
                return out;
            });
        }

        public List<int[]> structuresNear(int cx, int cz, int r) {
            int reach = r + 160;
            List<int[]> out = new ArrayList<>();
            for (int x = Math.floorDiv(cx - reach, 16); x <= Math.floorDiv(cx + reach, 16); x++)
                for (int z = Math.floorDiv(cz - reach, 16); z <= Math.floorDiv(cz + reach, 16); z++)
                    for (int[] b : boxesOf(x, z)) if (b[0] <= cx + r && b[2] >= cx - r && b[1] <= cz + r && b[3] >= cz - r) out.add(b);
            return out;
        }

        /** Same rule as Stage 0-E preflight v2: only FLUID inside the 32x32x18 volume (disk) is a safety failure; ordinary rock is excavated by construction. */
        public String preflight(Chamber c, Measure m, int cx, int cz, int floorY) {
            if (floorY < ChamberCore.REF_Y_MIN || floorY > ChamberCore.REF_Y_MAX) return "REFERENCE_Y_OUT_OF_BAND";
            BlockPos.MutableBlockPos p = new BlockPos.MutableBlockPos();
            int fluid = 0;
            for (int dx = 0; dx < ChamberCore.SUIT_W; dx++) for (int dz = 0; dz < ChamberCore.SUIT_W; dz++) {
                double ex = dx + 0.5 - 16, ez = dz + 0.5 - 16;
                if (m == Measure.DISK32 && ex * ex + ez * ez > 256) continue;
                for (int dy = 0; dy < ChamberCore.SUIT_H; dy++)
                    if (!level.getBlockState(p.set(cx - 16 + dx, floorY + dy, cz - 16 + dz)).getFluidState().isEmpty()) fluid++;
            }
            return fluid > 0 ? "FINAL_TERRAIN_FLUID blocked=" + fluid : null;
        }
    }

    // ------------------------------------------------------------------------------------------------ construction (server thread)
    private static void constructionStep(Runtime rt) throws Exception {
        if (rt.current != null) { advanceCurrent(rt); return; }
        List<int[]> pts = focusPoints(rt);
        St05Stage0FLive.Res pick = null; long bestD = Long.MAX_VALUE;
        for (List<St05Stage0FLive.Res> list : rt.reserved.values()) for (St05Stage0FLive.Res r : list) {
            if (rt.finished.contains(r.id())) continue;
            State s = Construction.load(rt.journal, r.id()).state;
            boolean unfinished = s == State.PLANNED || s == State.APPLYING || s == State.APPLIED;      // interrupted earlier: always continue (recovery)
            boolean terminal = s == State.VERIFIED || s == State.CONSTRUCTION_FAILED || s == State.QUARANTINED;
            if (terminal) { rt.finished.add(r.id()); continue; }
            long d = Long.MAX_VALUE;
            for (int[] pt : pts) { long dx = r.cx() - pt[0], dz = r.cz() - pt[1]; d = Math.min(d, dx * dx + dz * dz); }
            boolean near = d <= (long) TRIGGER_BLOCKS * TRIGGER_BLOCKS;
            if (!unfinished && !near) continue;
            if (unfinished) d = -1;
            if (d < bestD) { bestD = d; pick = r; }
        }
        if (pick == null) return;
        rt.current = pick; rt.currentSince = rt.server.getTickCount();
        St05Stage0FLive.forceChunks(rt.level, pick, true);
        LOG.info("[ST05-NATURAL] construction preparing id={} center={},{} floorY={}", pick.id(), pick.cx(), pick.cz(), pick.floorY());
    }

    private static boolean chunksReady(Runtime rt, St05Stage0FLive.Res r) {
        int R = St05Stage0FLive.R;
        for (int x = Math.floorDiv(r.cx() - R, 16); x <= Math.floorDiv(r.cx() + R, 16); x++)
            for (int z = Math.floorDiv(r.cz() - R, 16); z <= Math.floorDiv(r.cz() + R, 16); z++)
                if (rt.level.getChunkSource().getChunkNow(x, z) == null) return false;
        return true;
    }

    private static void advanceCurrent(Runtime rt) throws Exception {
        St05Stage0FLive.Res r = rt.current;
        if (!chunksReady(rt, r)) {
            if (rt.server.getTickCount() - rt.currentSince > 20 * 60 * 10) { LOG.warn("[ST05-NATURAL] chunks not ready after 10 min id={}; retrying later", r.id()); St05Stage0FLive.forceChunks(rt.level, r, false); rt.current = null; }
            return;
        }
        try {
            long t0 = System.nanoTime();
            Map<String, Object> d = St05Stage0FLive.handle(rt.server, rt.level, rt.world, rt.journal, r, -1, true, null);
            LOG.info("[ST05-NATURAL] construction id={} center={},{} state_at_entry={} final_state={} verify_failures={} plan_mismatches={} ms={}", r.id(), r.cx(), r.cz(), d.get("state_at_entry"), d.get("final_state"), d.get("verify_failures"), d.get("plan_mismatches"), (System.nanoTime() - t0) / 1_000_000);
            State s = Construction.load(rt.journal, r.id()).state;
            if (s == State.VERIFIED || s == State.CONSTRUCTION_FAILED || s == State.QUARANTINED) rt.finished.add(r.id());
        } finally {
            St05Stage0FLive.forceChunks(rt.level, r, false);
            rt.current = null;
        }
    }

    // ------------------------------------------------------------------------------------------------ persistence
    private static final class RegionFile {
        long seed; String summary = "";
        final List<String> lines = new ArrayList<>();
        final List<St05Stage0FLive.Res> reservations = new ArrayList<>();
    }

    private static final String MAGIC = "ST05-NATURAL-REGION-1";

    private static void writeRegion(Path p, RegionFile rf) throws IOException {
        StringBuilder sb = new StringBuilder(MAGIC + " algo=" + ChamberCore.ALGO + " params=" + PARAMS.name() + "/" + MEASURE + " seed=" + rf.seed + " universe=" + (2 * UNIVERSE_RADIUS + 1) + "x" + (2 * UNIVERSE_RADIUS + 1) + "\n");
        for (St05Stage0FLive.Res r : rf.reservations) sb.append("RES ").append(r.id()).append(' ').append(r.cx()).append(' ').append(r.cz()).append(' ').append(r.floorY()).append('\n');
        for (String l : rf.lines) sb.append("DEC ").append(l).append('\n');
        String digest = ChamberCore.sha256(sb.toString()).substring(0, 16);   // body only: readRegion verifies exactly these bytes
        sb.append("END ").append(digest).append('\n');
        Path tmp = p.resolveSibling(p.getFileName() + ".tmp");
        Files.writeString(tmp, sb.toString(), StandardCharsets.UTF_8);
        Files.move(tmp, p, StandardCopyOption.ATOMIC_MOVE, StandardCopyOption.REPLACE_EXISTING);
    }

    private static RegionFile readRegion(Path p, long seed) {
        try {
            List<String> ls = Files.readAllLines(p, StandardCharsets.UTF_8);
            if (ls.size() < 2 || !ls.get(0).startsWith(MAGIC) || !ls.get(0).contains(" seed=" + seed + " ")) return null;
            String last = ls.get(ls.size() - 1);
            StringBuilder body = new StringBuilder();
            for (int i = 0; i < ls.size() - 1; i++) body.append(ls.get(i)).append('\n');
            if (!last.equals("END " + ChamberCore.sha256(body.toString()).substring(0, 16))) return null;
            RegionFile rf = new RegionFile();
            rf.seed = seed;
            for (String l : ls) if (l.startsWith("RES ")) { String[] t = l.split(" "); rf.reservations.add(new St05Stage0FLive.Res(t[1], Integer.parseInt(t[2]), Integer.parseInt(t[3]), Integer.parseInt(t[4]))); }
            return rf;
        } catch (Exception e) { return null; }
    }

    private static void quarantine(Path p) {
        try { Files.move(p, p.resolveSibling(p.getFileName() + ".quarantine-" + System.currentTimeMillis()), StandardCopyOption.ATOMIC_MOVE); } catch (IOException ignored) { }
        LOG.warn("[ST05-NATURAL] unreadable region record quarantined (it will be rescanned): {}", p.getFileName());
    }

    private static int[] parseRegionName(String n) {
        String[] t = n.substring(2, n.length() - 4).split("_");
        try { return t.length == 2 ? new int[]{Integer.parseInt(t[0]), Integer.parseInt(t[1])} : null; } catch (NumberFormatException e) { return null; }
    }

    private static long key(int x, int z) { return ((long) x << 32) ^ (z & 0xFFFFFFFFL); }
}
